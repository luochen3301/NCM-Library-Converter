SUPPORTED_LANGUAGES = {"system", "en", "zh_CN"}


def resolve_language(language: str | None) -> str:
    value = language if language in SUPPORTED_LANGUAGES else "system"
    if value != "system":
        return value
    system_locale = (locale.getlocale()[0] or "").lower()
    return "zh_CN" if system_locale.startswith("zh") else "en"


