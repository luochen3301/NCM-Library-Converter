@dataclass
class Translator:
    language: str = "system"

    @property
    def resolved_language(self) -> str:
        return resolve_language(self.language)

    def t(self, key: str, **values: object) -> str:
        catalog = TRANSLATIONS.get(self.resolved_language, TRANSLATIONS["en"])
        template = catalog.get(key, TRANSLATIONS["en"].get(key, key))
        if not values:
            return template
        return template.format(**values)
